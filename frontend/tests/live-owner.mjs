// Live run against the REAL backend and built SPA. Env: BASE, OWNER_KEY, OUT (json file for the links)
import { chromium } from 'playwright'
import fs from 'node:fs'
const BASE = process.env.BASE, OWNER = process.env.OWNER_KEY, OUT = process.env.OUT
const res = []
const check = (n, ok, i = '') => { res.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${ok ? '' : '  -> ' + i}`) }
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1000, height: 900 } })
const page = await ctx.newPage()
const logs = [], urls = []
page.on('console', (m) => logs.push(m.text()))
page.on('pageerror', (e) => logs.push('pageerror ' + e.message))
page.on('request', (r) => urls.push(r.url()))
await page.goto(BASE + '/')
await page.getByRole('button', { name: /I own this server/ }).waitFor({ timeout: 10000 })
check('access screen shown with no credentials', true)
await page.screenshot({ path: OUT + '.access.png' })
await page.getByRole('button', { name: /I own this server/ }).click()
await page.locator('form.access-form:not([hidden]) input').last().fill('wrong-key-wrong-key-wrong-key')
await page.getByRole('button', { name: 'Save owner key' }).click()
await page.waitForTimeout(1000)
check('wrong owner key rejected (still on access screen)', await page.getByRole('button', { name: 'Save owner key' }).isVisible())
await page.locator('form.access-form:not([hidden]) input').last().fill(OWNER)
await page.getByRole('button', { name: 'Save owner key' }).click()
await page.waitForTimeout(1500)
await page.screenshot({ path: OUT + '.owner.png' })
const tabs = await page.locator('nav.tabbar button').allInnerTexts()
check('owner sees 4 tabs', tabs.length === 4, tabs.join('|'))
await page.goto(BASE + '/#/build?b=test-two-floor')
await page.waitForTimeout(1500)
check('Share panel present for owner', await page.getByText('Share this building').isVisible())
check('New building present for owner', await page.getByText('New building').first().isVisible())
const links = {}
for (const role of ['viewer', 'editor']) {
  await page.getByRole('radio', { name: new RegExp('^' + role, 'i') }).check()
  await page.getByLabel('Label (optional)').fill('e2e-' + role)
  await page.getByRole('button', { name: 'Create link' }).click()
  const box = page.locator('.share-made input[type=text]')
  await box.waitFor({ timeout: 8000 })
  links[role] = await box.inputValue()
  check(`${role} link created, shape ok`, new RegExp('^' + BASE.replace(/[.]/g, '\\.') + '/#/join\\?b=test-two-floor&t=').test(links[role]), links[role])
  await page.getByRole('button', { name: /Done|Close|Hide|Dismiss/ }).first().click().catch(() => {})
}
await page.waitForTimeout(500)
const rows = await page.locator('.invite-row').allInnerTexts()
console.log(rows)
check('invites listed (no token text)', rows.length >= 2 && !rows.join().includes(links.viewer.split('t=')[1]))
fs.writeFileSync(OUT, JSON.stringify(links))
check('owner key not in any request URL', urls.every((u) => !u.includes(OWNER)))
check('owner key not in console', logs.every((l) => !l.includes(OWNER)))
check('no tokens in URL', !page.url().includes(OWNER))
console.log('console:', logs.slice(0, 10))
await browser.close()
process.exit(res.every(Boolean) ? 0 : 1)
